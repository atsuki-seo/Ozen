set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
refgen="$here/../tools/refgen/refgen.py"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cases=0
failed=0

action() {
  printf '{"kind":"action","name":"%s","module":"%s","local":%s,"params":[%s],"output":{"text":"T<shape: peeled>"},"members":[{"uses":[{"text":"Peeler"}],"for":{"text":"1..2 min"}}]}' "$@"
}
x_param='{"name":"x","type":{"text":"T<shape: whole | shape: inShell, doneness >= done>","alts":[[{"axis":"shape","op":":","value":"whole"}],[{"axis":"shape","op":":","value":"inShell"},{"axis":"doneness","op":">=","value":"done"}]]},"default":null},{"name":"size","type":{"text":"Length in 0 mm<.."},"default":{"text":"3 mm"}}'
defs() {
  printf '{"schemaVersion":1,"definitions":[%s,%s,%s%s]}\n' \
    "$(action zest std.prelude false "$x_param")" \
    "$(action secretPeel std.prelude true "$x_param")" \
    "$(action userPeel book.soup false "$x_param")" "${1:-}"
}
defs > "$work/defs.json"
defs ",$(action grate std.prelude false "$x_param")" > "$work/defs-more.json"
printf 'OZNI_DIAG(SYN001, SYN, invalidUtf8, ERROR)\nOZNI_DIAG(SAF009, SAF, rawFishOnBoard, WARNING)\n' > "$work/diag.def"
cat > "$work/en.ftl" <<'FTL'
## Actions
action-zest = { $x-kind ->
    [lemon] Zest the lemon { $x }
   *[other] Zest { $x } finely
}
    .name = zest
diag-invalid-utf8 = The file is not valid UTF-8 at { $arg1 }
FTL
printf '# L\n\n<!-- ai-guide:begin -->\n## Quick syntax\n\nrecipe r {}\n<!-- ai-guide:end -->\n' > "$work/language.md"

gen() {
  python3 -B "$refgen" --definitions "$1" --diag "$work/diag.def" --phrases "$work/en.ftl" \
    --language "$work/language.md" --out "$2" "${@:3}"
}

check() {
  local name=$1 cond=$2
  cases=$((cases + 1))
  if ! eval "$cond"; then
    echo "FAIL $name: $cond" >&2
    failed=$((failed + 1))
  fi
}

gen "$work/defs.json" "$work/a" > /dev/null
std="$work/a/std.md"
diag="$work/a/diagnostics.md"
check std-only-public "grep -q '^## \`zest\`' $std && ! grep -q secretPeel $std && ! grep -q userPeel $std"
check params-and-state "grep -qF '\`size\`: \`Length in 0 mm<..\`, default \`3 mm\`' $std &&
  grep -qF '\`x\` is \`shape: whole\` or \`shape: inShell, doneness >= done\`' $std"
check phrase-text "grep -qF 'Recipe text: \"Zest <x> finely\"' $std"
check every-diagnostic "grep -q '^## SYN001 \`invalidUtf8\`' $diag && grep -q '^## SAF009 \`rawFishOnBoard\`' $diag &&
  grep -qx -- '- Severity: warning' $diag"
check diag-text "grep -qx -- '- Message: The file is not valid UTF-8 at <arg1>' $diag"
check diag-words "grep -qx -- '- Message: raw fish on board' $diag"
check header "for f in std.md diagnostics.md ai-guide.md; do head -n 1 $work/a/\$f | grep -q 'Generated by tools/refgen/refgen.py.*Do not edit' || exit 1; done"
gen "$work/defs.json" "$work/b" > /dev/null
check same-bytes "diff -r $work/a $work/b > /dev/null"
check guide-order "grep -n -e '^## Quick syntax' -e '^## Standard actions' -e '^## Diagnostics' -e '^## Work loop' $work/a/ai-guide.md |
  cut -d: -f2- | tr '\n' ';' | grep -qx '## Quick syntax;## Standard actions;## Diagnostics;## Work loop;'"
check check-clean "gen $work/defs.json $work/a --check | grep -qx 'refgen: 3 files, 0 differ'"
set +e
out=$(gen "$work/defs-more.json" "$work/a" --check 2>&1)
status=$?
set -e
check check-new-action "[ $status -eq 1 ] && grep -q 'differs: .*std.md' <<< \"\$out\" && grep -q 'differs: .*ai-guide.md' <<< \"\$out\" &&
  ! grep -q 'diagnostics.md' <<< \"\$out\""

echo "refgen: $cases cases, $failed failed"
[ "$failed" -eq 0 ]
