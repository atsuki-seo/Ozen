import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = "<!-- Generated by tools/refgen/refgen.py from {sources}. Do not edit; run the generator. -->"
GUIDE_LIMIT = 65536


def kebab(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", name).lower()


def words(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r" \1", name).lower()


def read_phrases(path):
    phrases, key, lines = {}, None, []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^([a-z][a-z0-9-]*) = ?(.*)$", line)
        if m:
            if key:
                phrases[key] = lines
            key, lines = m.group(1), [m.group(2)]
        elif key and line.startswith(" ") and not line.strip().startswith("."):
            lines.append(line.strip())
        elif key and not line.startswith(" "):
            phrases[key] = lines
            key, lines = None, []
    if key:
        phrases[key] = lines
    out = {}
    for k, ls in phrases.items():
        text = ls[0]
        if text.strip().endswith("->") or not text.strip():
            default = [l for l in ls[1:] if l.startswith("*[")]
            text = re.sub(r"^\*\[[^\]]*\]\s*", "", default[0]) if default else ""
        out[k] = re.sub(r"\{ *\$([a-z0-9-]+) *\}", r"<\1>", text).strip()
    return out


def read_diags(path):
    out = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^OZNI_DIAG\((\w+), *(\w+), *(\w+), *(\w+)\)", line.strip())
        if m:
            out.append(m.groups())
    return out


def read_definitions(args):
    if args.definitions:
        return json.load(open(args.definitions, encoding="utf-8"))
    r = subprocess.run([args.ozen, "debug", "definitions"], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"refgen: {args.ozen} debug definitions failed: {r.stderr.strip()}")
    return json.loads(r.stdout)


def std_actions(defs):
    acts = [d for d in defs["definitions"]
            if d["kind"] == "action" and d.get("module", "").startswith("std.") and not d.get("local")]
    return sorted(acts, key=lambda a: a["name"])


def type_text(t):
    if isinstance(t, dict):
        return t.get("text", "")
    return str(t)


def param_text(p):
    s = f"{p['name']}: {type_text(p['type'])}"
    if p.get("default") is not None:
        s += f" = {type_text(p['default'])}"
    return s


def requirements(a):
    reqs = []
    for p in a["params"]:
        t = p["type"]
        if isinstance(t, dict) and t.get("alts"):
            alts = []
            for alt in t["alts"]:
                parts = []
                for c in alt:
                    if "axis" in c:
                        sep = ": " if c["op"] == ":" else f" {c['op']} "
                        parts.append(f"{c['axis']}{sep}{c['value']}")
                    else:
                        parts.append(c.get("bare", ""))
                alts.append(", ".join(parts))
            reqs.append((p["name"], alts))
    return reqs


def uses_lines(members, indent=""):
    out = []
    for m in members:
        if "uses" in m:
            names = ", ".join(f"`{type_text(u)}`" for u in m["uses"])
            when = f" for `{type_text(m['for'])}`" if m.get("for") else ""
            out.append(f"{indent}- Uses {names}{when}")
        elif "variant" in m:
            out.append(f"{indent}- Variant `{m['variant']}`:")
            out.extend(uses_lines(m.get("members", []), indent + "  "))
    return out


def gen_std(defs, phrases):
    acts = std_actions(defs)
    out = [HEADER.format(sources="`ozen debug definitions` and `phrases/en.ftl`"), "",
           "# Standard library actions", "",
           f"`std` defines {len(acts)} actions. Each entry gives the call, the sentence a recipe text uses,",
           "the parameters with their types, the state each input must be in, and the equipment it uses.",
           "A type such as `T<shape: peeled>` means any ingredient `T` in that state; `|` separates",
           "alternatives.", ""]
    for a in acts:
        out.append(f"## `{a['name']}`")
        out.append("")
        out.append("```")
        result = f" -> {type_text(a['output'])}" if a.get("output") else ""
        out.append(f"{a['name']}({', '.join(param_text(p) for p in a['params'])}){result}")
        out.append("```")
        out.append("")
        text = phrases.get("action-" + kebab(a["name"]))
        if text:
            out.append(f"Recipe text: \"{text}\"")
            out.append("")
        out.append("Parameters:")
        out.append("")
        for p in a["params"]:
            default = f", default `{type_text(p['default'])}`" if p.get("default") is not None else ""
            out.append(f"- `{p['name']}`: `{type_text(p['type'])}`{default}")
        out.append("")
        reqs = requirements(a)
        if reqs:
            out.append("Requires:")
            out.append("")
            for name, alts in reqs:
                out.append(f"- `{name}` is " + " or ".join(f"`{x}`" for x in alts))
            out.append("")
        uses = uses_lines(a["members"])
        if uses:
            out.extend(uses)
            out.append("")
    return "\n".join(out)


def diag_text(name, phrases):
    return phrases.get("diag-" + kebab(name)) or words(name)


def gen_diagnostics(diags, phrases):
    out = [HEADER.format(sources="`core/src/diag_codes.def` and `phrases/en.ftl`"), "",
           "# Diagnostics", "",
           f"`ozen check` reports {len(diags)} kinds of diagnostics. Each has a code, a name, a category",
           "and a default severity; `<arg1>` and the like stand for the values in the message.", ""]
    for code, cat, name, sev in diags:
        out.append(f"## {code} `{name}`")
        out.append("")
        out.append(f"- Category: {cat}")
        out.append(f"- Severity: {sev.lower()}")
        out.append(f"- Message: {diag_text(name, phrases)}")
        out.append("")
    return "\n".join(out)


def cell(s):
    return s.replace("|", "\\|")


def gen_guide(language, acts, diags, phrases):
    m = re.search(r"^<!-- ai-guide:begin -->\n(.*?)^<!-- ai-guide:end -->$", language, re.S | re.M)
    if not m:
        raise SystemExit("refgen: reference/language.md has no ai-guide markers")
    quick = m.group(1).strip("\n")
    out = [HEADER.format(sources="`reference/language.md`, `ozen debug definitions`, `core/src/diag_codes.def` "
                                 "and `phrases/en.ftl`"), "",
           "# Ozen guide for AI agents", "",
           "This file is the whole guide: the syntax, the standard actions, the diagnostics and the loop to",
           "follow. The full reference is in `language.md`, `std.md` and `diagnostics.md` next to it.", "",
           quick, "",
           "## Standard actions", "",
           "| Action | Parameters | Required state |",
           "| --- | --- | --- |"]
    for a in acts:
        params = ", ".join(param_text(p) for p in a["params"])
        reqs = "; ".join(f"{n}: " + " or ".join(alts) for n, alts in requirements(a)) or "any"
        out.append(f"| `{a['name']}` | `{cell(params)}` | {cell(reqs)} |")
    out += ["", "## Diagnostics", "",
            "| Code | Name | Message |",
            "| --- | --- | --- |"]
    for code, cat, name, sev in diags:
        out.append(f"| {code} | `{name}` | {cell(diag_text(name, phrases))} |")
    out += ["", "## Work loop", "",
            "1. Write or change the recipe in a `.ozen` file.",
            "2. Run `ozen check --format json FILE` and read every diagnostic.",
            "3. Fix every error (severity `error`) and rerun the check until it reports 0 errors.",
            "4. Run `ozen render --kind recipe FILE` and read the recipe text to see that it says what you meant.",
            ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description="Generate the Ozen reference files.")
    ap.add_argument("--ozen", default=os.path.join(ROOT, "build/core-gcc-release/ozen"))
    ap.add_argument("--definitions")
    ap.add_argument("--diag", default=os.path.join(ROOT, "core/src/diag_codes.def"))
    ap.add_argument("--phrases", default=os.path.join(ROOT, "phrases/en.ftl"))
    ap.add_argument("--language", default=os.path.join(ROOT, "reference/language.md"))
    ap.add_argument("--out", default=os.path.join(ROOT, "reference"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    phrases = read_phrases(args.phrases)
    diags = read_diags(args.diag)
    defs = read_definitions(args)
    files = {
        "std.md": gen_std(defs, phrases),
        "diagnostics.md": gen_diagnostics(diags, phrases),
        "ai-guide.md": gen_guide(open(args.language, encoding="utf-8").read(), std_actions(defs), diags, phrases),
    }
    if len(files["ai-guide.md"].encode("utf-8")) > GUIDE_LIMIT:
        print(f"refgen: ai-guide.md is larger than {GUIDE_LIMIT} bytes", file=sys.stderr)
        return 1
    changed = 0
    for name in sorted(files):
        path = os.path.join(args.out, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == files[name]:
            continue
        changed += 1
        if args.check:
            print(f"differs: {os.path.relpath(path, ROOT) if path.startswith(ROOT) else path}", file=sys.stderr)
        else:
            os.makedirs(args.out, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(files[name])
    print(f"refgen: {len(files)} files, {changed} {'differ' if args.check else 'updated'}")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
